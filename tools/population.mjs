/** 省级代码前两位 → 默认人口（万人） */
export const PROVINCE_DEFAULT = {
  65: 70, 54: 35, 63: 50, 15: 110, 62: 160, 64: 140, // 新疆 西藏 青海 内蒙古 甘肃 宁夏
  23: 220, 22: 230, 21: 260, 52: 280, 53: 260,       // 东北、贵州、云南
};
export const DEFAULT_POP = 330;

export function popOf(name, adcode) {
  const short = String(name || '').replace(/(市|地区|自治州|盟|特别行政区)$/, '');
  if (POP[short] != null) return POP[short];
  const pre = String(adcode || '').slice(0, 2);
  return PROVINCE_DEFAULT[pre] ?? DEFAULT_POP;
}
